'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
test('pinned assessment extraction, confirmation, v9 generation, correction and preview in demo Firestore', async () => {
  process.env.GCLOUD_PROJECT = 'demo-quaerens-crm4'; process.env.FIRESTORE_EMULATOR_HOST = '127.0.0.1:8080';
  const runtime = require('../tools/local-handlers.cjs').createLocalHandlers();
  const id = 'synthetic-assessment-' + require('node:crypto').randomUUID(), uid = id + '-lister', manager = id + '-manager';
  const db = runtime.db, call = (suffix, data, actor = uid) => runtime.handlers['crm4AssessmentAssistant' + suffix]({ auth: { uid: actor }, data: { leadId: id, ...data } });
  try {
    await db.collection('crm4Memberships').doc(uid).set({ active: true, workspaceId: 'CRM4', role: 'lister' });
    await db.collection('crm4Memberships').doc(manager).set({ active: true, workspaceId: 'CRM4', role: 'manager' });
    await db.collection('users').doc(manager).set({ assessmentCapabilities: ['assessmentIssuer'] });
    await db.collection('crm4Leads').doc(id).set({ workspaceId: 'CRM4', assignedToUid: uid, claimType: 'foam_insulation', firstName: 'Synthetic', lastName: 'Assessment', email: 'assessment@example.test', mobile: '07700900000', addressLine1: '1 Synthetic Street', town: 'Test Town', postcode: 'ZZ1 1ZZ', country: 'United Kingdom' });
    await assert.rejects(call('Analyse', { narrative: 'CRM4_SYNTHETIC_ASSESSMENT' }, manager), e => e.code === 'permission-denied');
    const extraction = await call('Analyse', { narrative: 'CRM4_SYNTHETIC_ASSESSMENT: damp after installation; separate treatment and removal reported.', caseContext: { sameAsClientAddress: true } });
    assert(extraction.output); assert.equal(extraction.cacheHit, false);
    const confirmed = await call('ConfirmReview', { artifactId: extraction.id, reviewedExtraction: extraction.output });
    const draft = await call('GenerateDraft', { artifactId: confirmed.id });
    assert.equal(draft.status, 'DRAFT');
    const assessmentRef = db.collection('professionalAssessments').doc(draft.assessmentId);
    const first = (await assessmentRef.get()).data();
    assert.equal(first.generationContractVersion, 'assessment-generation-v9');
    assert.equal((await call('GenerateDraft', { artifactId: confirmed.id })).idempotent, true);
    const preview = await call('PreviewDraftPdf', {}, manager);
    assert.equal(Buffer.from(preview.content, 'base64').subarray(0, 4).toString(), '%PDF');
    assert.deepEqual((await assessmentRef.get()).data(), first, 'preview is read-only');
    const correction = structuredClone(confirmed.output); correction.missingInformation.push('Additional synthetic scope confirmation');
    const corrected = await call('SaveCorrections', { artifactId: confirmed.id, correctedExtraction: correction });
    const regenerated = await call('GenerateDraft', { artifactId: corrected.id });
    assert.equal(regenerated.assessmentId, draft.assessmentId); assert.equal(regenerated.qarReference, draft.qarReference);
    assert.equal((await assessmentRef.get()).data().revision, 2);
    assert.equal((await call('ReprojectDraft', {}, manager)).result, 'ALREADY_CURRENT');
    await assert.rejects(call('ReprojectDraft', {}), e => e.code === 'permission-denied');
    assert.equal(runtime.providerReceipts.length, 0);
    const finalised = await call('Finalise', {});
    assert.equal(finalised.status, 'COMPLETED');
    assert.equal(finalised.clientDeliveryStatus, 'SENT');
    assert.equal(finalised.archiveDeliveryStatus, 'SENT');
    assert.equal(runtime.storageObjects.size, 2);
    assert.equal(runtime.providerReceipts.length, 2);
    await assert.rejects(call('ReprojectDraft', {}, manager), e => e.code === 'failed-precondition');
    assert.equal((await call('Finalise', {})).idempotent, true);
    const closer = id + '-closer';
    await db.collection('crm4Memberships').doc(closer).set({ active: true, workspaceId: 'CRM4', role: 'closer' });
    const invoke = (name, actor, data) => runtime.handlers[name]({ auth: { uid: actor }, data: { leadId: id, ...data } });
    await assert.rejects(invoke('crm4ManagerUpdateLead', uid, { action: 'APPROVE' }), e => e.code === 'permission-denied');
    assert.equal((await invoke('crm4ManagerUpdateLead', manager, { action: 'APPROVE' })).currentStage, 'approved');
    assert.equal((await invoke('crm4ManagerUpdateLead', manager, { action: 'APPROVE' })).idempotent, true);
    const appointment = { closerUid: closer, mode: 'book', appointmentDate: '2099-01-12', appointmentTime: '12:00' };
    assert.equal((await invoke('crm4ManagerSendToCloser', manager, appointment)).status, 'APPOINTMENT_BOOKED');
    assert.equal((await invoke('crm4ManagerSendToCloser', manager, appointment)).idempotent, true);
    // Recording a synthetic commercial decision never invokes a payment API.
    const deal = { paymentOptionId: 'stripe_case_specific', customAgreedFeeAmount: 950 };
    assert.equal((await invoke('crm4CloserRecordClosedDeal', closer, deal)).status, 'CLOSED_DEAL_AWAITING_PAYMENT');
    assert.equal((await invoke('crm4CloserRecordClosedDeal', closer, deal)).idempotent, true);
    await db.collection('crm4AdministrationOnboardingSlots').doc(id).set({ date: '2099-01-12', startTime: '12:00', status: 'available' });
    await assert.rejects(invoke('crm4CloserBookAdministrationOnboarding', closer, { slotId: id }), e => e.code === 'failed-precondition');
    const currentLead = (await db.collection('crm4Leads').doc(id).get()).data();
    assert.equal(currentLead.paymentStatus, 'not_requested');
    assert(currentLead.actionHistory.some(e => e.action === 'closed_deal_awaiting_payment'));
    assert(runtime.providerReceipts.every(r => r.delivered === false));
    await assert.rejects(call('Finalise', {}), e => e.code === 'permission-denied');
    assert.equal(runtime.providerReceipts.length, 2);
    console.log('CRM4 assessment lifecycle: extraction -> confirmed review -> v9 draft -> PDF -> correction -> same-QAR revision 2');
  } finally { await runtime.close(); }
});
